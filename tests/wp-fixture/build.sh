#!/usr/bin/env bash
# Rebuild the "Atelier Lumière" WordPress 7.1.4 fixture from scratch (fully reproducible):
#   1. fresh copy of WordPress into site/ + SQLite Database Integration plugin + db.php drop-in
#   2. wp-config.php + mu-plugin
#   3. install.php   -> non-interactive install
#   4. seed.php      -> users, terms, media, posts, pages, comments, menus, app password
#   5. export.php    -> export.xml (WXR produced by WordPress' own export_wp())
#   6. inventory.php -> fixture.json + FIXTURE.md
#   7. start.sh      -> PHP built-in server on http://127.0.0.1:8081
#   8. verify.sh     -> smoke tests (HTTP + REST + application password)
# Everything previously in site/ (database included) is deleted.
set -euo pipefail

BASE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SITE="${BASE}/site"
WP_REF="${WP_REF:-/tmp/wp-ref/wordpress}"
WP_VERSION=7.1.4
SQLITE_ZIP="${BASE}/vendor/sqlite-database-integration-3.1.2.zip"
PLUGIN_DIR="${SITE}/wp-content/plugins/sqlite-database-integration"

echo "==> Stopping any running fixture server"
[ -f "${BASE}/server.pid" ] && kill "$(cat "${BASE}/server.pid")" 2>/dev/null || true
pkill -f '^([^ ]*/)?php -S 127\.0\.0\.1:8081( |$)' 2>/dev/null || true
rm -f "${BASE}/server.pid"

echo "==> Fresh WordPress ${WP_VERSION} copy in ${SITE}"
if [ ! -f "${WP_REF}/wp-includes/version.php" ]; then
	echo "    ${WP_REF} not found, downloading wordpress-${WP_VERSION}.zip"
	tmp="$(mktemp -d)"
	curl -sSfL -o "${tmp}/wordpress.zip" "https://wordpress.org/wordpress-${WP_VERSION}.zip"
	unzip -q "${tmp}/wordpress.zip" -d "${tmp}"
	WP_REF="${tmp}/wordpress"
fi
grep -q "\$wp_version = '${WP_VERSION}'" "${WP_REF}/wp-includes/version.php" || { echo "WordPress reference is not ${WP_VERSION}" >&2; exit 1; }
rm -rf "${SITE}" "${BASE}/debug.log"
cp -a "${WP_REF}" "${SITE}"

echo "==> SQLite Database Integration plugin + wp-content/db.php drop-in"
if [ ! -f "${SQLITE_ZIP}" ]; then
	mkdir -p "${BASE}/vendor"
	curl -sSfL -o "${SQLITE_ZIP}" "https://downloads.wordpress.org/plugin/sqlite-database-integration.3.1.2.zip"
fi
unzip -q "${SQLITE_ZIP}" -d "${SITE}/wp-content/plugins/"
# Same placeholder substitution as the plugin's sqlite_plugin_copy_db_file() (activate.php).
sed -e "s#{SQLITE_IMPLEMENTATION_FOLDER_PATH}#${PLUGIN_DIR}#g" \
	-e "s#{SQLITE_PLUGIN}#sqlite-database-integration/load.php#g" \
	"${PLUGIN_DIR}/db.copy" >"${SITE}/wp-content/db.php"

echo "==> wp-config.php"
cat >"${SITE}/wp-config.php" <<'PHP'
<?php
/**
 * WordPress 7.1.4 test fixture "Atelier Lumière" - SQLite edition.
 * Generated by /tmp/wp-test/build.sh (do not edit by hand, rebuild instead).
 */

// The database is SQLite (wp-content/db.php drop-in from the "SQLite Database Integration" plugin).
// The MySQL constants are unused but WordPress expects them to exist.
define( 'DB_NAME', 'wordpress' );
define( 'DB_USER', '' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', '' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
// Fixed database location (instead of the plugin's randomized default path).
define( 'DB_PATH', __DIR__ . '/wp-content/database/.ht.sqlite' );

// Fixed keys and salts: this is a local, throw-away test fixture.
define( 'AUTH_KEY',         'fixture-atelier-lumiere-auth-key-0001' );
define( 'SECURE_AUTH_KEY',  'fixture-atelier-lumiere-secure-auth-key-0002' );
define( 'LOGGED_IN_KEY',    'fixture-atelier-lumiere-logged-in-key-0003' );
define( 'NONCE_KEY',        'fixture-atelier-lumiere-nonce-key-0004' );
define( 'AUTH_SALT',        'fixture-atelier-lumiere-auth-salt-0005' );
define( 'SECURE_AUTH_SALT', 'fixture-atelier-lumiere-secure-auth-salt-0006' );
define( 'LOGGED_IN_SALT',   'fixture-atelier-lumiere-logged-in-salt-0007' );
define( 'NONCE_SALT',       'fixture-atelier-lumiere-nonce-salt-0008' );

$table_prefix = 'wp_';

// Hermetic fixture: no outgoing HTTP (oEmbed lookups, update checks...), no WP-Cron, no auto-updates.
// Keeps the database stable no matter how often the site is crawled.
define( 'WP_HTTP_BLOCK_EXTERNAL', true );
define( 'DISABLE_WP_CRON', true );
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_AUTO_UPDATE_CORE', false );
define( 'FS_METHOD', 'direct' );

// Errors are logged, never displayed (they would corrupt REST/XML responses).
define( 'WP_DEBUG', true );
define( 'WP_DEBUG_DISPLAY', false );
define( 'WP_DEBUG_LOG', dirname( __DIR__ ) . '/debug.log' );
@ini_set( 'display_errors', '0' );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
PHP

echo "==> mu-plugin"
mkdir -p "${SITE}/wp-content/mu-plugins"
cat >"${SITE}/wp-content/mu-plugins/fixture-tweaks.php" <<'PHP'
<?php
/**
 * Plugin Name: Atelier Lumière fixture tweaks
 * Description: Test fixture only. Enables Application Passwords over plain HTTP (http://127.0.0.1:8081) and disables outgoing e-mail (no MTA).
 */

// Application Passwords normally require HTTPS (or WP_ENVIRONMENT_TYPE=local).
add_filter( 'wp_is_application_passwords_available', '__return_true' );

// Never try to send e-mail (new comments, password changes...): wp_mail() returns false immediately.
add_filter( 'pre_wp_mail', '__return_false' );
PHP

echo "==> Installing WordPress"
php "${BASE}/install.php"

echo "==> Seeding content"
php "${BASE}/seed.php"

echo "==> WXR export"
php "${BASE}/export.php"

echo "==> Inventory (fixture.json + FIXTURE.md)"
php "${BASE}/inventory.php"

echo "==> Starting server"
"${BASE}/start.sh"

echo "==> Smoke tests"
"${BASE}/verify.sh"
